package dev.radarfcs.core;

/**
 * Вид летящего снаряда-цели (перехват). Отслеживаются только крупные: снаряды больших пушек и ракеты; мелкие
 * (патроны автопушек и пулемётов, ракеты ракетных блоков) - нет, их бывает слишком много.
 */
public enum ProjectileType {
    /** Снаряд большой пушки CBC и аддонов (болванка, фугасный, бронебойный...). */
    SHELL,
    /** Ракета (CBC Advanced Technologies, CBC Enchanced Shells и т. п.). */
    ROCKET
}
