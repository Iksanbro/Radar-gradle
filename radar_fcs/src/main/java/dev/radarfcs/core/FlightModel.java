package dev.radarfcs.core;

/**
 * Динамика снаряда в вертикальной плоскости выстрела. Единицы: блоки, тики.
 * Все силы (тяга, сопротивление, гравитация) лежат в этой плоскости, поэтому
 * полёт описывается двумя координатами: горизонтальной дальностью и высотой.
 */
public interface FlightModel {
    /** Начальная скорость, блоков/тик. */
    double muzzleSpeed();

    /** Ускорение вдоль вектора скорости на тике t: тяга (+) минус сопротивление (-). */
    double along(int tick, double speed);

    /** Вертикальное ускорение на тике t (гравитация, обычно отрицательная). */
    double vertical(int tick);

    /** Максимальное время полёта (время жизни снаряда), тики. */
    int maxTicks();
}
