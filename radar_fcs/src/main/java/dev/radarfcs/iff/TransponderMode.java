package dev.radarfcs.iff;

/** Что транспондер «свой» делает своим (всё, что внутри: мобы, игроки, транспорт, снаряды, корабли). */
public enum TransponderMode {
    /** Сублевел (корабль Sable / Create Aeronautics) или контрапшен, на котором стоит транспондер, и всё в его пределах. */
    SUBLEVEL,
    /** Всё в заданном радиусе вокруг транспондера (на корабле - вокруг его текущего положения). */
    RADIUS,
    /** Корабль (контрапшен) и всё в заданном расстоянии от его границ; не на корабле - как радиус. */
    SUBLEVEL_AND_DISTANCE;

    /** Используется ли радиус (расстояние). */
    public boolean usesRadius() {
        return this != SUBLEVEL;
    }
}
