package dev.radarfcs.iff;

/** Что транспондер «свой» делает своим. */
public enum TransponderMode {
    /** Сублевел (корабль Sable / Create Aeronautics) или контрапшен, на котором стоит транспондер, со всем на нём. */
    SUBLEVEL,
    /** Всё в заданном радиусе вокруг транспондера (на корабле - вокруг его текущего положения). */
    RADIUS
}
